use super::*;

/// `int()` of a float is exact at any size, as CPython's
/// `PyLong_FromDouble` is: each case's text is CPython's.
#[test]
fn int_of_a_float_is_exact_at_any_size() {
    let cases: [(f64, Value); 8] = [
        (-9.2e18, Value::Integer(-9_200_000_000_000_000_000)),
        (-9_223_372_036_854_775_808.0, Value::Integer(i64::MIN)),
        (-1e19, Value::BigInteger("-10000000000000000000".into())),
        (
            1.5e300,
            Value::BigInteger(
                "1500000000000000078757140382806630373056702871662238732373781173267703\
                 6869833622936795570626206717960655566657493258172654137848530406458634\
                 6718827718006047427258080138986370560674535069218213508905342985245619\
                 9917621678558451461320111979114170213741868888183230085264257173504208\
                 294580298189100810240"
                    .into(),
            ),
        ),
        (2.9, Value::Integer(2)),
        (
            9_223_372_036_854_775_808.0,
            Value::BigInteger("9223372036854775808".into()),
        ),
        (
            -2.5e38,
            Value::BigInteger("-249999999999999984927291592900794646528".into()),
        ),
        (
            1e300,
            Value::BigInteger(
                "1000000000000000052504760255204420248704468581108159154915854115511802457988908\
                 1957863713750804478640437044438328838781769425232353604305756447921847867069828\
                 4838720092657580373783023379478809005936895323497079994508111903896764088007465\
                 2742780142494579258788820056842838115669472196386865459400540160"
                    .into(),
            ),
        ),
    ];
    for (number, expected) in cases {
        assert_eq!(int_of_float(number), Ok(expected), "{number}");
    }
    assert_eq!(int_of_float(f64::NAN), Err(FloatToInt::NaN));
    assert_eq!(int_of_float(f64::NEG_INFINITY), Err(FloatToInt::Infinite));
}
